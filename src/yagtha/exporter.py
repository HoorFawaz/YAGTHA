"""Write the export bundle inside ``output/`` only.

A bundle is one folder per rule::

    output/<rule name>/
        original_rule.yml
        improved_rule.yml        (only when a fix was proposed)
        regression_cases.json    (only when a fix was proposed)
        test_regression.py       (only when a fix was proposed)
        analysis.json
        report.md

Path safety: the output folder must resolve inside the allowed root
(``./output`` by default), the bundle name is reduced to safe characters,
file names are fixed constants, and symbolic links are refused, so no input
can make YAGTHA write anywhere else.
"""

from __future__ import annotations

import io
import re
import zipfile
from collections.abc import Mapping
from pathlib import Path

from yagtha.errors import ExportError

DEFAULT_ROOT = Path("output")
MAX_NAME_LENGTH = 64

ORIGINAL_RULE = "original_rule.yml"
IMPROVED_RULE = "improved_rule.yml"
REGRESSION_CASES = "regression_cases.json"
REGRESSION_TEST = "test_regression.py"
ANALYSIS = "analysis.json"
REPORT = "report.md"
BUNDLE_FILES = (ORIGINAL_RULE, IMPROVED_RULE, REGRESSION_CASES, REGRESSION_TEST, ANALYSIS, REPORT)

# Static test file: it contains no value taken from the rule or the events.
REGRESSION_TEST_SOURCE = '''"""Regression tests generated by YAGTHA.

Run with ``pytest`` from this folder. They check that the improved rule still
catches every variant it caught when it was exported, and still ignores the
benign events.
"""

from pathlib import Path

import pytest

from yagtha.evaluator import matches
from yagtha.models import Expected
from yagtha.rule_loader import load_rule
from yagtha.verifier import load_cases

HERE = Path(__file__).resolve().parent
RULE = load_rule(HERE / "improved_rule.yml")
CASES = load_cases(HERE / "regression_cases.json")


@pytest.mark.parametrize("case", CASES, ids=[case.name for case in CASES])
def test_case(case):
    assert matches(RULE, case.event) == (case.expected is Expected.MATCH)
'''

_UNSAFE = re.compile(r"[^a-z0-9_-]+")


def bundle_name(rule_path: Path) -> str:
    """Safe folder name from the rule file name, e.g. ``mimikatz``."""
    name = _UNSAFE.sub("_", rule_path.stem.casefold()).strip("_-")[:MAX_NAME_LENGTH]
    return name or "rule"


def resolve_output_dir(out: Path, root: Path = DEFAULT_ROOT) -> Path:
    """Resolve ``out`` and check it is ``root`` or a folder inside it."""
    allowed = root.resolve()
    target = out.resolve()
    if target != allowed and allowed not in target.parents:
        raise ExportError(f"output folder {out} must be inside {root}/")
    return target


def write_bundle(out: Path, name: str, files: Mapping[str, str], root: Path = DEFAULT_ROOT) -> Path:
    """Write ``files`` (bundle file name -> text) to ``out/name`` and return that folder.

    Files of an earlier bundle that are not part of this one are removed, so a
    bundle never mixes two runs.
    """
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,63}", name):
        raise ExportError(f"invalid bundle name '{name}'")
    unknown = set(files) - set(BUNDLE_FILES)
    if unknown:
        raise ExportError(f"unknown bundle files: {', '.join(sorted(unknown))}")
    base = resolve_output_dir(out, root)
    bundle = base / name
    _refuse_links(root.resolve(), bundle)
    bundle.mkdir(parents=True, exist_ok=True)
    for file_name in BUNDLE_FILES:
        path = bundle / file_name
        if path.is_symlink():
            raise ExportError(f"refusing to write through symbolic link {path}")
        if file_name in files:
            path.write_text(files[file_name], encoding="utf-8", newline="\n")
        elif path.is_file():
            path.unlink()
    return bundle


def _refuse_links(root: Path, bundle: Path) -> None:
    """Refuse a bundle path that goes through a symbolic link below the root."""
    current = bundle
    while current != root and root in current.parents:
        if current.is_symlink():
            raise ExportError(f"refusing to write through symbolic link {current}")
        current = current.parent


def bundle_zip(name: str, files: Mapping[str, str]) -> bytes:
    """The bundle as a zip archive in memory (used by the web UI; nothing touches disk).

    Entries are ``<name>/<file>`` with the same checks as ``write_bundle`` and a
    fixed timestamp, so the archive is deterministic.
    """
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,63}", name):
        raise ExportError(f"invalid bundle name '{name}'")
    unknown = set(files) - set(BUNDLE_FILES)
    if unknown:
        raise ExportError(f"unknown bundle files: {', '.join(sorted(unknown))}")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for file_name in BUNDLE_FILES:
            if file_name in files:
                info = zipfile.ZipInfo(f"{name}/{file_name}", date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(info, files[file_name].encode("utf-8"))
    return buffer.getvalue()
