"""Produce the Markdown report of a full YAGTHA run.

The report is deterministic (no timestamps, stable order), so running the
same rule on the same events always gives the same file. Every value that
comes from a rule or an event is untrusted, so it is escaped before it is
put in a table cell or inline code.
"""

from __future__ import annotations

from collections.abc import Sequence
from enum import StrEnum

from yagtha.models import Analysis, Expected, Improvement, RegressionCase, Verification


class Verdict(StrEnum):
    """Overall result of a run."""

    ROBUST = "ROBUST"
    PASSED = "PASSED"
    FAILED = "FAILED"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT EVIDENCE"
    NOT_DETECTED = "NOT DETECTED"


VERDICT_TEXT = {
    Verdict.ROBUST: "No tested variation evades the rule.",
    Verdict.PASSED: (
        "The improved rule catches more variants, loses nothing the original caught "
        "and adds no false positive."
    ),
    Verdict.FAILED: "The improved rule loses detections or adds false positives; do not use it.",
    Verdict.INSUFFICIENT_EVIDENCE: (
        "Variants evade the rule, but the events hold no unchanged evidence to build a "
        "safe fix from."
    ),
    Verdict.NOT_DETECTED: (
        "The rule does not detect any baseline event, so there is nothing to make robust."
    ),
}


def verdict(improvement: Improvement, verification: Verification) -> Verdict:
    """Decide the overall verdict."""
    original = verification.original
    baselines = len(original.outcomes) - len(original.variants)
    if baselines and len(original.undetected_baselines) == baselines:
        return Verdict.NOT_DETECTED
    if not improvement.changed:
        return Verdict.INSUFFICIENT_EVIDENCE if original.findings else Verdict.ROBUST
    return Verdict.PASSED if verification.passed else Verdict.FAILED


def render_report(
    improvement: Improvement,
    verification: Verification,
    cases: Sequence[RegressionCase],
    bundle_files: Sequence[str] = (),
) -> str:
    """Render the whole run as Markdown."""
    before, after = verification.original, verification.improved
    rule = before.rule
    result = verdict(improvement, verification)
    lines = [
        f"# YAGTHA report: {_text(rule.title)}",
        "",
        f"**Verdict: {result.value}.** {VERDICT_TEXT[result]}",
        "",
        "## Summary",
        "",
        "| | Original rule | Improved rule |",
        "| --- | --- | --- |",
        f"| Rule id | `{_code(rule.id)}` | {_improved_id(improvement)} |",
        f"| Baseline events detected | {_detected(before)} | {_detected(after)} |",
        f"| Variants evading | {len(before.evaded)} of {len(before.variants)} "
        f"| {len(after.evaded)} of {len(after.variants)} |",
        f"| Benign events matched | {len(verification.benign_hits_original)} of "
        f"{verification.benign_total} | {len(verification.benign_hits_improved)} of "
        f"{verification.benign_total} |",
        "",
    ]
    lines += _evasions(before)
    lines += _changes(improvement)
    if improvement.changed:
        lines += _verification(verification, cases)
        fence = _fence(improvement.yaml_text)
        lines += ["## Improved rule", "", f"{fence}yaml", improvement.yaml_text.rstrip(), fence, ""]
    lines += _variants(before, after if improvement.changed else None)
    if bundle_files:
        lines += ["## Bundle", ""]
        lines += [f"- `{_code(name)}`" for name in bundle_files]
        lines.append("")
    lines += [
        "---",
        "",
        "Generated by YAGTHA. All values come from the input rule and events; "
        "nothing in this report was executed.",
    ]
    return "\n".join(lines) + "\n"


def _evasions(analysis: Analysis) -> list[str]:
    lines = ["## Evasions of the original rule", ""]
    for index in analysis.undetected_baselines:
        lines.append(f"- Baseline event {index} is not detected, so its variants are skipped.")
    if analysis.undetected_baselines:
        lines.append("")
    if not analysis.findings:
        return [*lines, "No variant evaded the rule.", ""]
    lines += [
        "| Event | Mutation | Selection | Field | Confidence | Why | Still visible in |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for f in analysis.findings:
        signals = ", ".join(f.remaining_signals) or "none"
        lines.append(
            f"| {f.event_index} | `{_code(f.mutation_name)}` | `{_code(f.condition)}` "
            f"| `{_code(f.field)}` | {f.confidence.value} | {_text(f.reason)} | {_text(signals)} |"
        )
    lines += [
        "",
        "*confirmed*: putting the field's original value back makes the rule fire again. "
        "*likely*: more than that one field is involved.",
        "",
    ]
    return lines


def _changes(improvement: Improvement) -> list[str]:
    lines = ["## Proposed changes", ""]
    if improvement.changed:
        lines += [f"- {_text(change)}" for change in improvement.changes]
        lines += ["", _text(improvement.rationale), ""]
    else:
        lines += [_text(improvement.rationale), ""]
    if improvement.unresolved:
        lines += ["### Not fixed automatically", ""]
        lines += [f"- {_text(note)}" for note in improvement.unresolved]
        lines.append("")
    return lines


def _verification(verification: Verification, cases: Sequence[RegressionCase]) -> list[str]:
    lines = ["## Verification", ""]
    lines += [f"- Fixed: `{_code(key)}`" for key in verification.fixed]
    for outcome in verification.improved.evaded:
        key = f"event{outcome.event_index}/{outcome.result.variant.mutation_name}"
        lines.append(f"- Still evades: `{_code(key)}`")
    lines += [f"- Regression: {_text(item)}" for item in verification.regressions]
    if not verification.regressions:
        lines.append("- Regressions: none")
    if verification.new_false_positives:
        shown = ", ".join(str(i) for i in verification.new_false_positives)
        lines.append(f"- New false positives on benign events: {shown}")
    else:
        lines.append("- New false positives: none")
    matching = sum(1 for case in cases if case.expected is Expected.MATCH)
    lines += [
        f"- Regression cases: {len(cases)} ({matching} must match, "
        f"{len(cases) - matching} must not match)",
        "",
    ]
    return lines


def _variants(before: Analysis, after: Analysis | None) -> list[str]:
    if after is None:
        lines = [
            "## All variants",
            "",
            "| Event | Mutation | Original rule |",
            "| --- | --- | --- |",
        ]
        for o in before.outcomes:
            lines.append(
                f"| {o.event_index} | `{_code(o.result.variant.mutation_name)}` "
                f"| {_hit(o.result.matched)} |"
            )
        return [*lines, ""]
    lines = [
        "## All variants",
        "",
        "| Event | Mutation | Original rule | Improved rule |",
        "| --- | --- | --- | --- |",
    ]
    for old, new in zip(before.outcomes, after.outcomes, strict=True):
        lines.append(
            f"| {old.event_index} | `{_code(old.result.variant.mutation_name)}` "
            f"| {_hit(old.result.matched)} | {_hit(new.result.matched)} |"
        )
    return [*lines, ""]


def _detected(analysis: Analysis) -> str:
    total = len(analysis.outcomes) - len(analysis.variants)
    return f"{total - len(analysis.undetected_baselines)} of {total}"


def _improved_id(improvement: Improvement) -> str:
    if not improvement.changed:
        return "not changed"
    return f"`{_code(improvement.new_rule.id)}`"


def _hit(matched: bool) -> str:
    return "caught" if matched else "**missed**"


def _text(value: str) -> str:
    """Plain text on one line, with Markdown and HTML control characters escaped."""
    single = " ".join(value.split())
    for char in "\\`*_[]<>|#":
        single = single.replace(char, f"\\{char}")
    return single


def _fence(block: str) -> str:
    """A backtick fence longer than any backtick run in ``block``, so it cannot be closed early."""
    longest = run = 0
    for char in block:
        run = run + 1 if char == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


def _code(value: str) -> str:
    """Text safe inside inline code: one line, no backticks, no pipes."""
    return " ".join(value.split()).replace("`", "'").replace("|", "/")
